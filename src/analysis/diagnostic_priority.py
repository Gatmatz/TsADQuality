    ax.set_xticks(x + width * (len(pivot.columns) - 1) / 2)
    ax.set_xticklabels(pivot.index)
    ax.set_ylabel("|AUC(only anomaly) - AUC(only normal)|")
    ax.set_title("Anomaly-Aware Location Sensitivity")
    ax.legend(frameon=False, ncol=2)
    fig.tight_layout()
    fig.savefig(OUTPUT_DIR / "anomaly_aware_location_gap.png", dpi=220)
