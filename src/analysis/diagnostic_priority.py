def dataframe_to_markdown(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    """Render a small DataFrame as Markdown without the optional tabulate dependency."""
    if df.empty:
        return "_No rows available._"

    def fmt(value) -> str:
        if pd.isna(value):
            return ""
        if isinstance(value, (float, np.floating)):
            return format(float(value), floatfmt)
        return str(value)

    columns = [str(c) for c in df.columns]
    rows = [[fmt(value) for value in row] for row in df.to_numpy()]
    widths = []
    for i, col in enumerate(columns):
        values = [row[i] for row in rows]
        widths.append(max(len(col), *(len(v) for v in values)))

    def render_row(values: list[str]) -> str:
        padded = [values[i].ljust(widths[i]) for i in range(len(values))]
        return "| " + " | ".join(padded) + " |"

    header = render_row(columns)
    separator = "| " + " | ".join("-" * w for w in widths) + " |"
    body = [render_row(row) for row in rows]
    return "\n".join([header, separator, *body])


