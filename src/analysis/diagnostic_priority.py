    pivot = (
        location_effect.groupby(["corruption_type", "model"], as_index=False)
        .agg(gap=("location_gap_abs", "mean"))
        .pivot(index="corruption_type", columns="model", values="gap")
    )
    if pivot.empty:
        return
    pivot = pivot[_ordered_models(pivot.columns)]
    fig, ax = plt.subplots(figsize=(8, 4))
    x = np.arange(len(pivot.index))
