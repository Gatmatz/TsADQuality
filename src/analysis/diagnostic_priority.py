def load_baseline_means() -> pd.DataFrame:
    path = RESULTS_DIR / "tables" / "baseline_final_subset.csv"
    if not path.exists():
        raise FileNotFoundError(f"Missing baseline table: {path}")

    df = pd.read_csv(path)
    if not {"model", "AUC_ROC", "AUC_PR", "VUS_ROC"}.issubset(df.columns):
        raise ValueError(f"Baseline table lacks required metric columns: {path}")

    df["model"] = normalize_model_names(df["model"])
    return (
        df.groupby("model", as_index=False)
        .agg(
            baseline_AUC_ROC=("AUC_ROC", "mean"),
            baseline_AUC_PR=("AUC_PR", "mean"),
            baseline_VUS_ROC=("VUS_ROC", "mean"),
            baseline_n=("file", "nunique"),
        )
        .copy()
    )


def _safe_float(value) -> float:
    try:
        if pd.isna(value):
            return np.nan
        return float(value)
    except Exception:
        return np.nan


def _format_value(value) -> str:
    if pd.isna(value):
        return ""
    if isinstance(value, (int, np.integer)):
        return str(value)
    if isinstance(value, (float, np.floating)):
        if abs(value - round(value)) < 1e-9:
            return str(int(round(value)))
        return f"{value:.4g}"
    return str(value)


def make_condition_label(row: pd.Series, fields: Iterable[str]) -> str:
    parts: list[str] = []
    for field in fields:
        if field in row.index and not pd.isna(row[field]) and str(row[field]) != "":
            parts.append(f"{field}={_format_value(row[field])}")
    if parts:
        return ", ".join(parts)
    if "condition" in row.index and not pd.isna(row["condition"]):
        return str(row["condition"])
    return "condition"


def compute_observed_severity(df: pd.DataFrame, exp: SingleExperiment) -> pd.Series:
    """Create a 0-1 severity proxy from each experiment's condition columns."""
    idx = df.index
    candidates: list[pd.Series] = []

    if "snr_db" in df.columns and df["snr_db"].notna().any():
        snr = pd.to_numeric(df["snr_db"], errors="coerce")
        # Lower SNR means more severe noise.
        denom = max(float(snr.max() - snr.min()), 1e-12)
        candidates.append((snr.max() - snr) / denom)

    if "fraction" in df.columns and df["fraction"].notna().any():
        frac = pd.to_numeric(df["fraction"], errors="coerce")
        max_frac = max(float(frac.max()), 1e-12)
        candidates.append(frac / max_frac)

    if "multiplier" in df.columns and df["multiplier"].notna().any():
        mult = pd.to_numeric(df["multiplier"], errors="coerce")
        max_mult = max(float(mult.max()), 1e-12)
        candidates.append(mult / max_mult)

    if "num_bursts" in df.columns and df["num_bursts"].notna().any():
        bursts = pd.to_numeric(df["num_bursts"], errors="coerce")
        max_bursts = max(float(bursts.max()), 1e-12)
        candidates.append(bursts / max_bursts)

    if "n_segments" in df.columns and df["n_segments"].notna().any():
        segments = pd.to_numeric(df["n_segments"], errors="coerce")
        max_segments = max(float(segments.max()), 1e-12)
        candidates.append(segments / max_segments)

    if "severity" in df.columns and df["severity"].notna().any():
        severity_map = {"low": 0.33, "med": 0.66, "medium": 0.66, "high": 1.0, "severe": 1.0}
        sev = df["severity"].astype(str).str.lower().map(severity_map)
        if sev.notna().any():
            candidates.append(sev)

    if not candidates:
        return pd.Series(np.nan, index=idx)

    stacked = pd.concat(candidates, axis=1)
    return stacked.mean(axis=1, skipna=True).clip(0.0, 1.0)


def load_single_impact_table(baseline: pd.DataFrame) -> pd.DataFrame:
    frames: list[pd.DataFrame] = []

    for exp in SINGLE_EXPERIMENTS:
        path = EXPERIMENTS_DIR / exp.relative_path
        if not path.exists():
            print(f"[WARN] Missing single summary: {path}")
            continue

        df = pd.read_csv(path)
        if "mean_AUC_ROC" not in df.columns or "model" not in df.columns:
            print(f"[WARN] Skipping {exp.name}: missing mean_AUC_ROC/model")
            continue

        df = df.copy()
        df["model"] = normalize_model_names(df["model"])
        df = df.merge(baseline, on="model", how="left")
        df = df[df["baseline_AUC_ROC"].notna()].copy()

        if df.empty:
            print(f"[WARN] Skipping {exp.name}: no matching model baselines")
            continue

        out = pd.DataFrame(
            {
                "experiment": exp.name,
                "defect_family": exp.defect_family,
                "family_group": FAMILY_GROUPS.get(exp.defect_family, exp.defect_family),
                "mechanism": exp.mechanism,
                "model": df["model"],
                "condition": df.apply(lambda r: make_condition_label(r, exp.condition_fields), axis=1),
                "n_runs": pd.to_numeric(df.get("n_runs", df.get("n", np.nan)), errors="coerce"),
                "baseline_AUC_ROC": df["baseline_AUC_ROC"],
                "mean_AUC_ROC": pd.to_numeric(df["mean_AUC_ROC"], errors="coerce"),
                "mean_AUC_PR": pd.to_numeric(df.get("mean_AUC_PR", np.nan), errors="coerce"),
                "mean_VUS_ROC": pd.to_numeric(df.get("mean_VUS_ROC", np.nan), errors="coerce"),
                "severity_proxy": compute_observed_severity(df, exp),
                "notes": exp.notes,
            }
        )
        out["auc_drop"] = out["baseline_AUC_ROC"] - out["mean_AUC_ROC"]
        out["positive_auc_drop"] = out["auc_drop"].clip(lower=0.0)
        out["auc_drop_pct"] = np.where(
            out["baseline_AUC_ROC"].abs() > 1e-12,
            100.0 * out["auc_drop"] / out["baseline_AUC_ROC"],
            np.nan,
        )
        frames.append(out)
        print(f"[INFO] Loaded single summary {exp.name}: {len(out)} rows")

    if not frames:
        return pd.DataFrame()

    table = pd.concat(frames, ignore_index=True)
    table = table.sort_values(["positive_auc_drop", "experiment"], ascending=[False, True])
    return table


def load_anomaly_aware_location_effect(baseline: pd.DataFrame) -> pd.DataFrame:
    path = EXPERIMENTS_DIR / "anomaly_aware_corruption" / "summary.csv"
    if not path.exists():
        print(f"[WARN] Missing anomaly-aware summary: {path}")
        return pd.DataFrame()

    df = pd.read_csv(path)
    df["model"] = normalize_model_names(df["model"])
    df = df.merge(baseline, on="model", how="left")
    df["auc_drop"] = df["baseline_AUC_ROC"] - df["mean_AUC_ROC"]
    df["positive_auc_drop"] = df["auc_drop"].clip(lower=0.0)

    grouped = (
        df.groupby(["corruption_type", "target_mode", "model"], as_index=False)
        .agg(
            mean_AUC_ROC=("mean_AUC_ROC", "mean"),
            mean_AUC_PR=("mean_AUC_PR", "mean"),
            mean_VUS_ROC=("mean_VUS_ROC", "mean"),
            mean_positive_auc_drop=("positive_auc_drop", "mean"),
            mean_corrupted_normal_points=("mean_corrupted_normal_points", "mean"),
            mean_corrupted_anomaly_points=("mean_corrupted_anomaly_points", "mean"),
        )
        .copy()
    )

    pivot = grouped.pivot_table(
        index=["corruption_type", "model"],
        columns="target_mode",
        values="mean_AUC_ROC",
        aggfunc="mean",
    ).reset_index()
    for col in ["only_normal", "only_anomaly", "mixed"]:
        if col not in pivot.columns:
            pivot[col] = np.nan

    pivot["location_gap_abs"] = (pivot["only_anomaly"] - pivot["only_normal"]).abs()
    pivot["anomaly_minus_normal_auc"] = pivot["only_anomaly"] - pivot["only_normal"]
    pivot["mechanism_reading"] = np.where(
        pivot["anomaly_minus_normal_auc"] < 0,
        "anomaly masking / false negatives",
        "signal amplification vs normal false positives",
    )

    return grouped.merge(
        pivot[
            [
                "corruption_type",
                "model",
                "only_normal",
                "only_anomaly",
                "mixed",
                "location_gap_abs",
                "anomaly_minus_normal_auc",
                "mechanism_reading",
            ]
        ],
        on=["corruption_type", "model"],
        how="left",
    )


def load_compound_tables(baseline: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    summary_path = EXPERIMENTS_DIR / "compound_corruptions" / "summary.csv"
    if summary_path.exists():
        df = pd.read_csv(summary_path)
        df["model"] = normalize_model_names(df["model"])
        df = df.merge(baseline, on="model", how="left")
        df["auc_drop"] = df["baseline_AUC_ROC"] - pd.to_numeric(df["mean_AUC_ROC"], errors="coerce")
        df["positive_auc_drop"] = df["auc_drop"].clip(lower=0.0)
        compound = df[df["condition_type"].astype(str).eq("compound")].copy()
        compound = compound.sort_values("positive_auc_drop", ascending=False)
    else:
        print(f"[WARN] Missing compound summary: {summary_path}")
        compound = pd.DataFrame()

    interaction_path = EXPERIMENTS_DIR / "compound_corruptions" / "interaction_summary.csv"
    if interaction_path.exists():
        interaction = pd.read_csv(interaction_path)
        interaction["model"] = normalize_model_names(interaction["model"])
    else:
        print(f"[WARN] Missing interaction summary: {interaction_path}")
        interaction = pd.DataFrame()

    shapley_path = EXPERIMENTS_DIR / "compound_corruptions" / "shapley_summary.csv"
    if shapley_path.exists():
        shapley = pd.read_csv(shapley_path)
        shapley["model"] = normalize_model_names(shapley["model"])
        shapley["family_group"] = shapley["corruption"].map(
            {"noise": "noise", "spikes": "spikes", "missing": "missing"}
        )
    else:
        print(f"[WARN] Missing Shapley summary: {shapley_path}")
        shapley = pd.DataFrame()

    return compound, interaction, shapley


def load_propagation_scope() -> pd.DataFrame:
    frames: list[pd.DataFrame] = []
    path = EXPERIMENTS_DIR / "propagation" / "propagation_summary.csv"
    if path.exists():
        df = pd.read_csv(path)
        df["source"] = "propagation"
        frames.append(df)

    path_multi = EXPERIMENTS_DIR / "propagation_multiscale" / "propagation_summary.csv"
    if path_multi.exists():
        df = pd.read_csv(path_multi)
        # Keep all scales; aggregation below absorbs the scale dimension.
        df["source"] = "propagation_multiscale"
        frames.append(df)

    if not frames:
        return pd.DataFrame()

    df = pd.concat(frames, ignore_index=True)
    df["model"] = normalize_model_names(df["model"])
    df["family_group"] = df["corruption_type"].map(
        {"noise": "noise", "spikes": "spikes", "missing": "missing", "freeze": "freeze"}
    )
    df = df[df["family_group"].notna()].copy()
    agg = (
        df.groupby("family_group", as_index=False)
        .agg(
            propagation_ratio=("mean_ratio", "mean"),
            propagation_ratio_max=("mean_ratio", "max"),
            far_zone_diff=("mean_diff_far", "mean"),
            far_zone_diff_max=("mean_diff_far", "max"),
        )
        .copy()
    )
    return agg


