def _ordered_models(columns: Iterable[str]) -> list[str]:
    cols = list(columns)
    ordered = [m for m in MODEL_ORDER if m in cols]
    ordered.extend([m for m in cols if m not in ordered])
    return ordered


def plot_single_impact_heatmap(single_table: pd.DataFrame) -> None:
    if single_table.empty:
        return
    pivot = single_table.pivot_table(
        index="defect_family",
        columns="model",
        values="positive_auc_drop",
        aggfunc="mean",
    )
    if pivot.empty:
        return
    pivot = pivot[_ordered_models(pivot.columns)]
    pivot = pivot.loc[pivot.mean(axis=1).sort_values(ascending=True).index]

    fig_h = max(6, 0.35 * len(pivot) + 2)
    fig, ax = plt.subplots(figsize=(9, fig_h))
    image = ax.imshow(pivot.values, aspect="auto", cmap="Reds")
    ax.set_xticks(range(len(pivot.columns)))
    ax.set_xticklabels(pivot.columns, rotation=30, ha="right")
    ax.set_yticks(range(len(pivot.index)))
    ax.set_yticklabels(pivot.index)
    ax.set_title("Mean Positive AUC Drop by Single Defect and Model")
    ax.set_xlabel("Model")
    ax.set_ylabel("Single defect family")
    fig.colorbar(image, ax=ax, label="Positive AUC drop")

    for i in range(pivot.shape[0]):
        for j in range(pivot.shape[1]):
            value = pivot.iloc[i, j]
            if pd.notna(value):
                ax.text(j, i, f"{value:.2f}", ha="center", va="center", fontsize=8)

    fig.tight_layout()
    fig.savefig(OUTPUT_DIR / "single_impact_heatmap.png", dpi=220)
    plt.close(fig)


