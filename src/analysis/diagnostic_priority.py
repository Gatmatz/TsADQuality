def _minmax(series: pd.Series) -> pd.Series:
    values = pd.to_numeric(series, errors="coerce")
    if values.notna().sum() == 0:
        return pd.Series(np.nan, index=series.index)
    min_v = float(values.min())
    max_v = float(values.max())
    if max_v - min_v < 1e-12:
        return pd.Series(1.0, index=series.index)
    return ((values - min_v) / (max_v - min_v)).clip(0.0, 1.0)


def build_single_priority(single_table: pd.DataFrame) -> pd.DataFrame:
    if single_table.empty:
        return pd.DataFrame()

    priority = (
        single_table.groupby(["defect_family", "family_group", "mechanism"], as_index=False)
        .agg(
            n_conditions=("condition", "count"),
            n_models=("model", "nunique"),
            mean_positive_auc_drop=("positive_auc_drop", "mean"),
            median_positive_auc_drop=("positive_auc_drop", "median"),
            max_positive_auc_drop=("positive_auc_drop", "max"),
            min_mean_AUC_ROC=("mean_AUC_ROC", "min"),
            mean_AUC_ROC=("mean_AUC_ROC", "mean"),
            mean_auc_drop_pct=("auc_drop_pct", "mean"),
            mean_severity_proxy=("severity_proxy", "mean"),
        )
        .copy()
    )
    priority["impact_score"] = _minmax(priority["mean_positive_auc_drop"])
    priority["worst_case_score"] = _minmax(priority["max_positive_auc_drop"])
    priority["single_priority_score"] = (
        0.65 * priority["impact_score"] + 0.35 * priority["worst_case_score"]
    )
    return priority.sort_values("single_priority_score", ascending=False)


def build_diagnostic_priority_index(
    single_priority: pd.DataFrame,
    location_effect: pd.DataFrame,
    shapley: pd.DataFrame,
    propagation: pd.DataFrame,
    transferability: pd.DataFrame,
) -> pd.DataFrame:
    if single_priority.empty:
        return pd.DataFrame()

    index = single_priority.copy()

    if not location_effect.empty:
        loc = (
            location_effect.groupby("corruption_type", as_index=False)
            .agg(location_gap_abs=("location_gap_abs", "mean"))
            .copy()
        )
        loc["family_group"] = loc["corruption_type"].map(
            {"noise": "noise", "spikes": "spikes", "missing": "missing"}
        )
        loc = loc.groupby("family_group", as_index=False).agg(
            location_sensitivity=("location_gap_abs", "mean")
        )
        loc["location_score"] = _minmax(loc["location_sensitivity"])
        index = index.merge(loc[["family_group", "location_sensitivity", "location_score"]], on="family_group", how="left")
    else:
        index["location_sensitivity"] = np.nan
        index["location_score"] = np.nan

    if not shapley.empty:
        shp = (
            shapley.groupby("family_group", as_index=False)
            .agg(
                compound_shapley_pct=("mean_pct", "mean"),
                compound_shapley_value=("mean_shapley", "mean"),
            )
            .copy()
        )
        shp["compound_score"] = _minmax(shp["compound_shapley_pct"])
        index = index.merge(shp, on="family_group", how="left")
    else:
        index["compound_shapley_pct"] = np.nan
        index["compound_shapley_value"] = np.nan
        index["compound_score"] = np.nan

    if not propagation.empty:
        prop = propagation.copy()
        prop["propagation_score"] = _minmax(prop["far_zone_diff"])
        index = index.merge(
            prop[
                [
                    "family_group",
                    "propagation_ratio",
                    "propagation_ratio_max",
                    "far_zone_diff",
                    "far_zone_diff_max",
                    "propagation_score",
                ]
            ],
            on="family_group",
            how="left",
        )
    else:
        index["propagation_score"] = np.nan

    if not transferability.empty:
        trans = transferability.copy()
        trans["transferability_score"] = _minmax(trans["transferability_jaccard"])
        index = index.merge(trans, on="family_group", how="left")
    else:
        index["transferability_score"] = np.nan

    component_weights = {
        "single_priority_score": 0.35,
        "location_score": 0.20,
        "compound_score": 0.20,
        "propagation_score": 0.15,
        "transferability_score": 0.10,
    }

    fixed_score = pd.Series(0.0, index=index.index)
    available_score = pd.Series(0.0, index=index.index)
    available_weight = pd.Series(0.0, index=index.index)
    evidence_axes = pd.Series(0, index=index.index)

    for col, weight in component_weights.items():
        if col not in index.columns:
            index[col] = np.nan
        values = pd.to_numeric(index[col], errors="coerce")
        fixed_score += values.fillna(0.0) * weight
        mask = values.notna()
        available_score += values.fillna(0.0) * weight
        available_weight += mask.astype(float) * weight
        evidence_axes += mask.astype(int)

    index["dpi_score"] = fixed_score
    index["dpi_available_weighted_score"] = np.where(available_weight > 0, available_score / available_weight, np.nan)
    index["evidence_axes"] = evidence_axes
    index["priority_rank"] = index["dpi_score"].rank(ascending=False, method="dense").astype("Int64")

    return index.sort_values(["dpi_score", "evidence_axes"], ascending=[False, False])


