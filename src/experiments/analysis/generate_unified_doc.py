    'ακόμα και σε απολύτως κανονικά τμήματα του σήματος. Καθώς η ισχύς του θορύβου αυξάνεται, αυτές οι τυχαίες μικρο-αραιώσεις αρχίζουν να παρουσιάζουν '
    'χαμηλότερη τοπική πυκνότητα από ό,τι η ίδια η πραγματική ανωμαλία. Ο αλγόριθμος αρχίζει έτσι να δίνει υψηλότερες βαθμολογίες σε φυσιολογικά σημεία '
