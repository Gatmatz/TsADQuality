    'τυχαίους διαχωρισμούς (random splits) του χώρου χαρακτηριστικών. Σε αντίθεση με το MP που υπολογίζει ακριβείς αποστάσεις, '
    'ή τον AE που προσπαθεί να αναπαράγει ακριβή σχήματα, το IForest λειτουργεί καθαρά γεωμετρικά: τα απομακρυσμένα σημεία απομονώνονται ταχύτερα. '
    'Όταν μια χρονοσειρά εμπεριέχει μια ακραία ανωμαλία (π.χ. μια απότομη κορυφή), το σημείο αυτό τοποθετείται εξαιρετικά μακριά '
