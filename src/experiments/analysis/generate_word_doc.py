    'Όταν το θορυβώδες σήμα τροφοδοτείται στον εκπαιδευμένο Autoencoder, το δίκτυο προσπαθεί να το περάσει μέσα από τον "λαιμό μπουκαλιού" (bottleneck). '
    'Επειδή είναι μαθηματικά αδύνατο να κωδικοποιηθεί ο τυχαίος θόρυβος σε έναν χαμηλοδιάστατο χώρο, η έξοδος του δικτύου '
    'είναι ουσιαστικά μια αυστηρά εξομαλυμένη (smoothed) εκδοχή της εισόδου, απηλλαγμένη από τις θορυβώδεις ακίδες. '
    'Συνεπώς, το σφάλμα ανακατασκευής (η διαφορά εισόδου-εξόδου) για τα κανονικά σημεία εκτοξεύεται, καθώς αντικατοπτρίζει πλέον την απουσία του θορύβου στην έξοδο. '
    'Αντίθετα, η πραγματική ανωμαλία παρουσιάζει πλέον παρόμοιο σφάλμα, καθώς το δίκτυο δίνει απλώς έναν μέσο όρο εξόδου για όλα τα σήματα που δεν αναγνωρίζει. '
