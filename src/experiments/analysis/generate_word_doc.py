    'Η προσθήκη μέτριου θορύβου προκαλεί μια γεωμετρική "διαστολή" στο νέφος των κανονικών σημείων, αυξάνοντας τη διασπορά τους, '
    'αλλά η πραγματική ανωμαλία εξακολουθεί να βρίσκεται εκτός αυτής της διευρυμένης ζώνης. '
    'Τα δέντρα απομόνωσης συνεχίζουν να την τέμνουν πρώτα. Η αποτυχία παρατηρείται μόνο όταν το πλάτος (variance) του θορύβου '
    'γίνει τόσο τεράστιο (στα αρνητικά SNR) ώστε να "καταπιεί" πλήρως το γεωμετρικό πλάτος της ανωμαλίας. Σε αυτό το ακραίο όριο, '
    'τα κανονικά σημεία γίνονται το ίδιο διάσπαρτα και "αραιά" (sparse) με την ανωμαλία, με αποτέλεσμα ο αλγόριθμος να απομονώνει τυχαίες '
    'κορυφές του θορύβου εξίσου γρήγορα με την ανωμαλία.'
