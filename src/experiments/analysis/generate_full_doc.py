    'του νέφους των κανονικών σημείων, ωστόσο η ανωμαλία βρίσκεται τόσο μακριά που παραμένει εύκολα διαχωρίσιμη '
    'από τα δέντρα στα πρώτα επίπεδα. Η εσωτερική ανάλυση του μήκους διαδρομής (path length) επιβεβαιώνει ότι η '
