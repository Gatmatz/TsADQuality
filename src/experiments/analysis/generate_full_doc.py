    'του θορύβου αυξάνεται τόσο πολύ που "καταπίνει" το γεωμετρικό πλάτος της ανωμαλίας. Τα κανονικά σημεία γίνονται εξίσου '
    'διάσπαρτα και "αραιά" (sparse) με την ανωμαλία στον χώρο χαρακτηριστικών, επιτρέποντας στα δέντρα απομόνωσης '
